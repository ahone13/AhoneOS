function initFavorites(content) {
  const board = content.querySelector('#fav-board');
  const boardBg = content.querySelector('#fav-board-bg');

  // Size the board to the corkboard image's real dimensions,
  // same as the layout tool did — keeps positions accurate.
  boardBg.onload = () => {
    board.style.width = boardBg.naturalWidth + 'px';
    board.style.height = boardBg.naturalHeight + 'px';
  };

  favLayout.forEach(item => {
    const el = document.createElement('div');
    el.className = 'fav-item';
    el.style.left = item.x + 'px';
    el.style.top = item.y + 'px';
    el.style.zIndex = item.z;
    el.style.transform = `rotate(${item.rotation}deg) scale(${item.scale})`;

    const img = document.createElement('img');
    img.src = 'assets/images/favorites/' + item.filename;

    el.appendChild(img);
    board.appendChild(el);
  });
}